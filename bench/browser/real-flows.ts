import { writeFileSync } from "node:fs";
import { Effect } from "effect";
import { Session } from "../../browser/dist/session.js";

type RealPage = { app: string; url: string; needle: string; baseline: number };

export const PAGES: RealPage[] = [
  { app: "mdn", url: "https://developer.mozilla.org/en-US/docs/Web/HTTP/Caching", needle: "arbitrary value generated by the server", baseline: 72004 },
  { app: "react", url: "https://react.dev/reference/react/useState", needle: "state variable", baseline: 61784 },
  { app: "github", url: "https://github.com/rust-lang/rust", needle: "Pull requests", baseline: 39000 },
  { app: "wikipedia", url: "https://en.wikipedia.org/wiki/HTTPS", needle: "secure implementation of HTTPS", baseline: 98356 },
  { app: "mdn", url: "https://developer.mozilla.org/en-US/docs/Web/HTTP/Caching", needle: "large number of variations", baseline: 70969 },
  { app: "react", url: "https://react.dev/reference/react/useState", needle: "previous state", baseline: 61891 },
  { app: "mdn", url: "https://developer.mozilla.org/en-US/docs/Web/HTTP/Caching", needle: "freshness", baseline: 70957 },
  { app: "github", url: "https://github.com/rust-lang/rust", needle: "Issues", baseline: 30443 },
  { app: "wikipedia", url: "https://en.wikipedia.org/wiki/HTTPS", needle: "Hypertext Transfer Protocol Secure", baseline: 139124 },
  { app: "mdn", url: "https://developer.mozilla.org/en-US/docs/Web/HTTP/Caching", needle: "shared cache", baseline: 70967 },
];

export async function runRealFlows(): Promise<void> {
  const session = await Effect.runPromise(Session.create());
  const rows: Array<Record<string, unknown>> = [];
  try {
    for (const page of PAGES) {
      const started = performance.now();
      const state = await Effect.runPromise(session.open(page.url));
      const ok = state.text.toLowerCase().includes(page.needle.toLowerCase());
      rows.push({
        app: page.app,
        url: page.url,
        needle: page.needle,
        state_tokens: state.tokens,
        baseline_tokens: page.baseline,
        ratio: Number((page.baseline / Math.max(state.tokens, 1)).toFixed(1)),
        ok,
        ms: Math.round(performance.now() - started),
      });
    }
  } finally {
    await Effect.runPromise(session.close());
  }
  const ok = rows.filter((row) => row.ok);
  const ratios = ok.map((row) => row.ratio as number).sort((a, b) => a - b);
  const summary = {
    checks: rows.length,
    pages: new Set(rows.map((row) => row.url)).size,
    ok: ok.length,
    median_ratio: ratios[Math.floor(ratios.length / 2)] ?? 0,
    min_ratio: Math.min(...ratios),
    max_ratio: Math.max(...ratios),
    baseline_total: rows.reduce((sum, row) => sum + (row.baseline_tokens as number), 0),
    ssg_total: rows.reduce((sum, row) => sum + (row.state_tokens as number), 0),
  };
  const data = { summary: { ...summary, total_ratio: Number((summary.baseline_total / summary.ssg_total).toFixed(1)) }, rows };
  writeFileSync(new URL("./real-flows.json", import.meta.url), JSON.stringify(data, null, 2));
  console.log(JSON.stringify(data.summary, null, 2));
}

await runRealFlows();
